# 0-based NLH coefficient tables: shape = (92, 92, 3)
# Use with z_i = atomic_numbers[idx_i] - 1, z_j = atomic_numbers[idx_j] - 1
# Stored in nhl_tables.npz next to this module (float64, lossless; they
# were Python literals here before, copied from the JAX so3lr_dev code).


def _load_nhl_tables():
    path = importlib.resources.files(__package__).joinpath("nhl_tables.npz")
    with path.open("rb") as fh, np.load(fh) as data:
        return data["NHL_AA"], data["NHL_BB"]


NHL_AA, NHL_BB = _load_nhl_tables()
